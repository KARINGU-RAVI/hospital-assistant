"""Builds build/runtime/ (the AgentCore CodeZip folder) and agentcore/agentcore.json for `agentcore deploy`.

Run (after `python data\\seed.py` and `python data\\build_index.py`):
    python scripts\\build_runtime.py

What it writes (all git-ignored):
- build/runtime/: agent/ code, data/ (hospital.db, chroma/, models/, faq/), main.py entry, pyproject.toml
  with pinned cloud dependencies, iam-policy.json (least privilege, real ARNs read from AWS)
- agentcore/agentcore.json: from the committed agentcore.template.json, plus environment variables taken
  from .env (API keys as plain-text runtime env vars: accepted for this one-day demo)

AWS calls: read-only only (bedrock.get_guardrail, bedrock-agentcore-control.get_memory) to get exact ARNs.
Verified: AgentCore CLI 1.2.0 agentcore.json schema (runtimes[].envVars [{name, value}],
additionalPolicies = JSON policy files relative to codeLocation); CodeZip limit 250 MB zipped / 750 MB
unzipped (AgentCore devguide, runtime-get-started-code-deploy-python).
"""
from __future__ import annotations

import importlib.metadata as metadata
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from agent.config import get_settings  # noqa: E402

AGENT_CODE = ROOT / "agent"
BUILD = ROOT / "build" / "runtime"
TEMPLATE = ROOT / "agentcore" / "agentcore.template.json"
CONFIG = ROOT / "agentcore" / "agentcore.json"
MAX_UNZIPPED_MB = 750

# Cloud dependencies (no streamlit / pytest / requests: the UI stays on the laptop). Pinned to the
# versions tested locally so the cloud runs the same code.
CLOUD_PACKAGES = [
    ("strands-agents", "strands-agents[gemini,openai]"),
    ("bedrock-agentcore", "bedrock-agentcore"),
    ("boto3", "boto3"),
    ("python-dotenv", "python-dotenv"),
    ("chromadb", "chromadb"),
    ("fastembed", "fastembed"),
    ("aws-opentelemetry-distro", "aws-opentelemetry-distro"),  # used by the AgentCore CLI templates
]
RAG_PACKAGES = {"chromadb", "fastembed"}

# Settings passed to the runtime as environment variables (names from .env.example).
ENV_NAMES = [
    "GEMINI_API_KEY", "GROQ_API_KEY", "OPENROUTER_API_KEY", "MODEL_CHAIN", "GEMINI_MODEL_ID", "GROQ_MODEL_ID",
    "OPENROUTER_MODEL_ID", "BEDROCK_MODEL_ID", "AWS_REGION", "GUARDRAILS_ENABLED", "GUARDRAIL_ID",
    "GUARDRAIL_VERSION", "MEMORY_ENABLED", "MEMORY_ID", "RAG_MODE", "RAG_MAX_DISTANCE",
    "HISTORY_MAX_MESSAGES", "HISTORY_MAX_TOKENS",
]

ENTRY = '''"""AgentCore Runtime entry (generated by scripts/build_runtime.py).

The bundled data is copied to /tmp first: the code folder may be read-only, and SQLite writes bookings.
Each runtime session has its own microVM, so bookings live only for that session (see README).
"""
import os
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORK = Path("/tmp/hospital-data")
if not WORK.exists():
    shutil.copytree(HERE / "data", WORK)
os.environ.setdefault("DB_PATH", str(WORK / "hospital.db"))
os.environ.setdefault("CHROMA_PATH", str(WORK / "chroma"))
os.environ.setdefault("MODELS_PATH", str(WORK / "models"))
os.environ.setdefault("FAQ_PATH", str(WORK / "faq"))

from agent.cli import setup_logging  # noqa: E402
from agent.main import app  # noqa: E402

if __name__ == "__main__":
    setup_logging()
    app.run()
'''


def pinned_requirements(rag_mode: str) -> list[str]:
    reqs = []
    for dist, spec in CLOUD_PACKAGES:
        if rag_mode == "keyword" and dist in RAG_PACKAGES:
            continue
        try:
            reqs.append(f"{spec}=={metadata.version(dist)}")
        except metadata.PackageNotFoundError:
            reqs.append(spec)  # not installed locally (e.g. the otel distro): let uv pick the latest
    return reqs


def pyproject(requirements: list[str]) -> str:
    deps = "\n".join(f'    "{r}",' for r in requirements)
    return f'''[build-system]
requires = ["hatchling"]
build-backend = "hatchling.build"

[project]
name = "hospital-frontdesk-runtime"
version = "1.0.0"
requires-python = ">=3.12"
dependencies = [
{deps}
]

[tool.hatch.build.targets.wheel]
packages = ["."]
'''


def iam_policy(guardrail_arn: str | None, memory_arn: str | None) -> dict:
    """Least privilege: apply OUR guardrail, write/read events and records of OUR memory only."""
    statements = []
    if guardrail_arn:
        statements.append({"Sid": "ApplyClinicGuardrail", "Effect": "Allow",
                           "Action": ["bedrock:ApplyGuardrail"], "Resource": [guardrail_arn]})
    if memory_arn:
        statements.append({"Sid": "UseClinicMemory", "Effect": "Allow",
                           "Action": ["bedrock-agentcore:CreateEvent", "bedrock-agentcore:RetrieveMemoryRecords"],
                           "Resource": [memory_arn]})
    return {"Version": "2012-10-17", "Statement": statements}


def resource_arns(settings) -> tuple[str | None, str | None]:
    """Exact ARNs via read-only AWS calls (no guessing of ARN formats)."""
    import boto3

    guardrail_arn = memory_arn = None
    if settings.guardrails_enabled and settings.guardrail_id:
        guardrail_arn = boto3.client("bedrock", region_name=settings.aws_region).get_guardrail(
            guardrailIdentifier=settings.guardrail_id, guardrailVersion=settings.guardrail_version)["guardrailArn"]
    if settings.memory_enabled and settings.memory_id:
        memory_arn = boto3.client("bedrock-agentcore-control", region_name=settings.aws_region).get_memory(
            memoryId=settings.memory_id)["memory"]["arn"]
    return guardrail_arn, memory_arn


def env_vars(settings) -> list[dict]:
    import os

    from agent.models import is_configured

    values = {name: os.getenv(name, "").strip() for name in ENV_NAMES}
    values["MODEL_CHAIN"] = ",".join(settings.model_chain)
    for provider in ("gemini", "groq", "openrouter"):  # don't ship keys of models that can't be used
        if provider not in settings.model_chain or not is_configured(provider, settings):
            values[f"{provider.upper()}_API_KEY"] = ""
    return [{"name": k, "value": v} for k, v in values.items() if v]


def agentcore_config(template: dict, envs: list[dict], has_policy: bool) -> dict:
    config = json.loads(json.dumps(template))
    runtime = config["runtimes"][0]
    runtime["envVars"] = envs
    if has_policy:
        runtime["additionalPolicies"] = ["iam-policy.json"]
    return config


def folder_mb(path: Path) -> float:
    return sum(f.stat().st_size for f in path.rglob("*") if f.is_file()) / 1e6


def copy_tree(src: Path, dst: Path) -> None:
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".locks"))


def build(settings, guardrail_arn: str | None, memory_arn: str | None) -> dict:
    """Assemble build/runtime and agentcore/agentcore.json. Returns a short summary (no secrets)."""
    data = ROOT / "data"
    needed = [data / "hospital.db", data / "faq"]
    if settings.rag_mode != "keyword":
        needed += [settings.chroma_path, settings.models_path]
    missing = [str(p.relative_to(ROOT)) for p in needed if not p.exists()]
    if missing:
        raise SystemExit(f"Missing {missing}: run python data\\seed.py and python data\\build_index.py first.")

    shutil.rmtree(BUILD, ignore_errors=True)
    BUILD.mkdir(parents=True)
    copy_tree(AGENT_CODE, BUILD / "agent")
    (BUILD / "data").mkdir()
    shutil.copy2(data / "hospital.db", BUILD / "data" / "hospital.db")
    copy_tree(data / "faq", BUILD / "data" / "faq")
    if settings.rag_mode != "keyword":
        copy_tree(settings.chroma_path, BUILD / "data" / "chroma")
        copy_tree(settings.models_path, BUILD / "data" / "models")
    (BUILD / "main.py").write_text(ENTRY, encoding="utf-8")
    requirements = pinned_requirements(settings.rag_mode)
    (BUILD / "pyproject.toml").write_text(pyproject(requirements), encoding="utf-8")

    policy = iam_policy(guardrail_arn, memory_arn)
    if policy["Statement"]:
        (BUILD / "iam-policy.json").write_text(json.dumps(policy, indent=2), encoding="utf-8")

    envs = env_vars(settings)
    template = json.loads(TEMPLATE.read_text(encoding="utf-8"))
    CONFIG.write_text(json.dumps(agentcore_config(template, envs, bool(policy["Statement"])), indent=2), encoding="utf-8")
    return {"code_and_data_mb": round(folder_mb(BUILD), 1), "requirements": requirements,
            "env_var_names": [e["name"] for e in envs], "policy_statements": [s["Sid"] for s in policy["Statement"]]}


def main() -> None:
    settings = get_settings()
    guardrail_arn, memory_arn = resource_arns(settings)
    summary = build(settings, guardrail_arn, memory_arn)
    print(f"Built {BUILD.relative_to(ROOT)} ({summary['code_and_data_mb']} MB before dependencies)")
    print("Dependencies:", ", ".join(summary["requirements"]))
    print("Runtime env vars (names only):", ", ".join(summary["env_var_names"]))
    print("IAM policy statements:", ", ".join(summary["policy_statements"]) or "none (switches off)")
    print(f"Wrote {CONFIG.relative_to(ROOT)} (git-ignored: it contains your API keys).")
    print("Note: the zipped package must stay under 250 MB (750 MB unzipped) including dependencies.")


if __name__ == "__main__":
    main()
